/**
 * Adds patients.patient_number to a database created before that column
 * existed, and gives every patient already in the table a number.
 *
 *   node scripts/add-patient-numbers.mjs
 *
 * Why this and not plain `npm run db:push`: adding an identity column in one
 * statement makes Postgres number the existing rows in *physical* order, which
 * is whatever order the pages happen to be in — so the oldest patient could
 * come out as #37. Here the column is added empty, filled in created_at order,
 * and only then turned into the identity sequence. Numbers then read as the
 * order people actually walked in.
 *
 * Safe to run twice: it does nothing when the column is already an identity.
 */
import { neonConfig, Pool } from "@neondatabase/serverless";
import ws from "ws";

try {
  process.loadEnvFile(".env");
} catch {
  // no .env — nothing to load
}

if (!process.env.DATABASE_URL) {
  console.error("DATABASE_URL topilmadi. Mahalliy JSON store buni o'zi bajaradi.");
  process.exit(1);
}

neonConfig.webSocketConstructor = ws;
const pool = new Pool({ connectionString: process.env.DATABASE_URL });

const { rows: existing } = await pool.query(`
  SELECT is_identity FROM information_schema.columns
  WHERE table_name = 'patients' AND column_name = 'patient_number'
`);

if (existing[0]?.is_identity === "YES") {
  console.log("patient_number allaqachon mavjud — hech narsa o'zgartirilmadi.");
  await pool.end();
  process.exit(0);
}

if (existing.length === 0) {
  await pool.query(`ALTER TABLE patients ADD COLUMN patient_number integer`);
  console.log("patient_number ustuni qo'shildi");
}

// Oldest patient gets #1. row_number() over created_at is the whole point of
// doing this by hand instead of letting ADD COLUMN ... IDENTITY fill it in.
const { rowCount: numbered } = await pool.query(`
  UPDATE patients p
  SET patient_number = seq.n
  FROM (
    SELECT id, row_number() OVER (ORDER BY created_at, id) AS n
    FROM patients
  ) seq
  WHERE p.id = seq.id AND p.patient_number IS NULL
`);
console.log(`${numbered} ta bemorga raqam berildi`);

const { rows: maxRows } = await pool.query(
  `SELECT coalesce(max(patient_number), 0) + 1 AS next FROM patients`,
);
const next = maxRows[0].next;

await pool.query(`ALTER TABLE patients ALTER COLUMN patient_number SET NOT NULL`);
await pool.query(
  `ALTER TABLE patients ALTER COLUMN patient_number
   ADD GENERATED BY DEFAULT AS IDENTITY (START WITH ${next})`,
);
console.log(`keyingi yangi bemor raqami: #${next}`);

await pool.end();
